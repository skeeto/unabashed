# ${x%p} and ${x%%p}
p() { printf '<%s>' "$@"; echo; }
x=archive.tar.gz
p "${x%.*}" "${x%%.*}" "${x%gz}" "${x%%gz}" "${x%nomatch}"
p "${x%?}" "${x%%?}" "${x%*}" "${x%%*}"
p "${x%[a-z]}" "${x%%[.]*}" "${x%.[!g]*}"
y='a*b*c'
p "${y%\**}" "${y%%\**}" "${y%'*c'}" "${y%"*c"}"
z='back\slash'
p "${z%\\*}" "${z#*\\}" ${z%'\'*}
w='}x}'
p "${w%\}}" "${w#\}}" "${w%'}'}"
